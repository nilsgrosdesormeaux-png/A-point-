// Teste migration-connecteurs-caisse.sql dans un vrai Postgres (PGlite, en
// mémoire) sans toucher au projet Supabase : normalisation, dédoublonnage,
// relance sans doublon, droits et RLS.
// Lancement : npm i --no-save @electric-sql/pglite@0.3.7 && node tests/caisse-migration.test.mjs

import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
// Socle minimal imitant Supabase (auth.users, rôles, ventes, produits tels qu'en prod).
await db.exec(`
  create schema auth; create table auth.users (id uuid primary key);
  create or replace function auth.uid() returns uuid language sql as $$ select null::uuid $$;
  create role anon; create role authenticated; create role service_role;
  create table ventes (id bigint generated by default as identity primary key, created_at timestamptz default now(),
    nom_produit text, quantite bigint, date_vente date, commercant_id uuid);
  create table produits (id bigint generated by default as identity primary key, created_at timestamptz default now(),
    commercant_id uuid default gen_random_uuid(), nom text, categorie_id text);
  insert into auth.users values ('00000000-0000-0000-0000-000000000001');
`);
await db.exec(fs.readFileSync(new URL('../migration-connecteurs-caisse.sql', import.meta.url), 'utf8'));
const C = '00000000-0000-0000-0000-000000000001';
const q = async (s, p) => (await db.query(s, p)).rows;

for (const [entree, attendu] of [['  Croissants ', 'croissant'], ['CROISSANT', 'croissant'], ['Éclair café', 'eclair cafe'], ['Gâteaux', 'gateau'], ['Bus', 'bus'], [null, '']]) {
  assert.equal((await q('select normaliser_nom_produit($1) n', [entree]))[0].n, attendu, String(entree));
}

// Existant : produit "Pain au chocolat", saisie manuelle du 29 (5) et du 28 (7).
await q(`insert into produits (commercant_id, nom) values ($1, 'Pain au chocolat')`, [C]);
await q(`insert into ventes (commercant_id, nom_produit, quantite, date_vente) values ($1,'Pain au chocolat',5,'2026-10-29'),($1,'pain au chocolat ',7,'2026-10-28')`, [C]);

const lignes = [
  { nom_produit: 'PAIN AU CHOCOLATS', quantite: 30, date_vente: '2026-10-29' },
  { nom_produit: 'Pain au chocolat', quantite: 2, date_vente: '2026-10-29' },
  { nom_produit: 'Baguette', quantite: 80.4, date_vente: '2026-10-29' },
  { nom_produit: 'Baguette', quantite: -3, date_vente: '2026-10-30' },
  { nom_produit: '  ', quantite: 9, date_vente: '2026-10-29' }
];
assert.equal((await q(`select enregistrer_ventes_caisse($1, $2::jsonb, 'sumup') n`, [C, JSON.stringify(lignes)]))[0].n, 3);
// Relance identique : aucun doublon.
await q(`select enregistrer_ventes_caisse($1, $2::jsonb, 'sumup')`, [C, JSON.stringify(lignes)]);

const v = await q(`select nom_produit, quantite::int, date_vente::text, source from ventes order by date_vente, nom_produit`);
console.log(v);
assert.deepEqual(v, [
  { nom_produit: 'pain au chocolat ', quantite: 7, date_vente: '2026-10-28', source: 'manuel' },
  { nom_produit: 'Baguette', quantite: 80, date_vente: '2026-10-29', source: 'sumup' },
  { nom_produit: 'Pain au chocolat', quantite: 32, date_vente: '2026-10-29', source: 'sumup' },
  { nom_produit: 'Baguette', quantite: 0, date_vente: '2026-10-30', source: 'sumup' }
]);
assert.deepEqual((await q('select nom from produits order by id')).map(r => r.nom), ['Pain au chocolat', 'Baguette']);

// Droits : seul service_role peut appeler la fonction d'enregistrement.
for (const role of ['anon', 'authenticated']) {
  assert.equal((await q(`select has_function_privilege('${role}', 'enregistrer_ventes_caisse(uuid,jsonb,text)', 'execute') ok`))[0].ok, false);
}
assert.equal((await q(`select has_function_privilege('service_role', 'enregistrer_ventes_caisse(uuid,jsonb,text)', 'execute') ok`))[0].ok, true);
// RLS active partout, secrets sans aucune policy.
const rls = await q(`select relname, relrowsecurity from pg_class where relname in ('connexions_caisse','connexions_caisse_secrets','etats_oauth_caisse')`);
assert.ok(rls.every(r => r.relrowsecurity));
assert.equal((await q(`select count(*)::int n from pg_policies where tablename in ('connexions_caisse_secrets','etats_oauth_caisse')`))[0].n, 0);

// v2 à v4 par-dessus, deux fois (idempotence) : clé personnelle Loyverse / Tactill acceptée.
for (let passage = 0; passage < 2; passage++) {
  for (const f of ['v2', 'v3', 'v4', 'v5', 'v6']) await db.exec(fs.readFileSync(new URL(`../migration-connecteurs-caisse-${f}.sql`, import.meta.url), 'utf8'));
}
await q(`insert into connexions_caisse (commercant_id, fournisseur) values ($1, 'loyverse'), ($1, 'tactill'), ($1, 'zelty'), ($1, 'popina')`, [C]);
await assert.rejects(q(`insert into connexions_caisse (commercant_id, fournisseur) values ($1, 'inconnue')`, [C]));
for (const role of ['anon', 'authenticated']) {
  for (const [table, droit] of [['connexions_caisse_secrets', 'select'], ['connexions_caisse_secrets', 'insert'], ['etats_oauth_caisse', 'select'], ['connexions_caisse', 'insert'], ['connexions_caisse', 'update'], ['journal_caisse', 'insert']]) {
    assert.equal((await q(`select has_table_privilege('${role}', '${table}', '${droit}') ok`))[0].ok, false, role + ' ' + droit + ' ' + table);
  }
}
assert.equal((await q(`select has_table_privilege('authenticated', 'connexions_caisse', 'select') ok`))[0].ok, true);
assert.equal((await q(`select count(*)::int n from pg_policies where tablename = 'connexions_caisse_secrets' or (tablename in ('connexions_caisse','journal_caisse') and cmd <> 'SELECT')`))[0].n, 0);

// v6 : Lightspeed Retail, ventes heure par heure, photo du rapport.
await q(`insert into connexions_caisse (commercant_id, fournisseur) values ($1, 'lightspeed_retail')`, [C]);
const h = (l) => q(`select enregistrer_ventes_horaires($1, '2026-10-29', $2, $3::jsonb) n`, [C, l.min, JSON.stringify(l.lignes)]);
await h({ min: 0, lignes: [{ nom_produit: 'baguettes', heure: 7, quantite: 10 }, { nom_produit: 'Baguette', heure: 7, quantite: 2 }, { nom_produit: 'Baguette', heure: 9, quantite: 5 }] });
await h({ min: 9, lignes: [{ nom_produit: 'Baguette', heure: 9, quantite: 6 }, { nom_produit: 'Baguette', heure: 10, quantite: 1 }, { nom_produit: 'Baguette', heure: 8, quantite: 99 }] });
await h({ min: 9, lignes: [{ nom_produit: 'Baguette', heure: 9, quantite: 6 }, { nom_produit: 'Baguette', heure: 10, quantite: 1 }] }); // relance : rien ne double
assert.deepEqual(await q(`select heure::int, nom_produit, quantite::int from ventes_horaires order by heure`), [
  { heure: 7, nom_produit: 'Baguette', quantite: 12 }, { heure: 9, nom_produit: 'Baguette', quantite: 6 }, { heure: 10, nom_produit: 'Baguette', quantite: 1 }]);
await assert.rejects(q(`insert into ventes_horaires values ($1, '2026-10-29', 7, 'Baguette', 1)`, [C])); // unique
await assert.rejects(q(`insert into ventes_horaires values ($1, '2026-10-29', 24, 'Pain', 1)`, [C]));   // heure 0-23
for (const role of ['anon', 'authenticated']) {
  for (const [obj, droit] of [['ventes_horaires', 'insert'], ['ventes_horaires', 'update'], ['lectures_ticket', 'insert']]) {
    assert.equal((await q(`select has_table_privilege('${role}', '${obj}', '${droit}') ok`))[0].ok, false, role + droit + obj);
  }
  assert.equal((await q(`select has_function_privilege('${role}', 'enregistrer_ventes_horaires(uuid,date,integer,jsonb)', 'execute') ok`))[0].ok, false);
}
assert.equal((await q(`select has_table_privilege('authenticated', 'ventes_horaires', 'select') ok`))[0].ok, true);
assert.equal((await q(`select has_function_privilege('authenticated', 'enregistrer_ventes_photo(date,jsonb,text)', 'execute') ok`))[0].ok, true);
// Photo : au nom du commerçant connecté, source « photo », une ligne de journal.
await assert.rejects(q(`select enregistrer_ventes_photo(current_date - 1, '[{"nom_produit":"Flan","quantite":3}]', 'test')`), /Non authentifie/);
await db.exec(`create or replace function auth.uid() returns uuid language sql as $$ select '${C}'::uuid $$;`);
assert.equal((await q(`select enregistrer_ventes_photo((now() at time zone 'Europe/Paris')::date - 1, '[{"nom_produit":"Flan","quantite":3},{"nom_produit":"flans","quantite":2},{"nom_produit":"","quantite":9}]', 'rapport.jpg') n`))[0].n, 1);
assert.deepEqual(await q(`select nom_produit, quantite::int, source from ventes where source = 'photo'`), [{ nom_produit: 'Flan', quantite: 5, source: 'photo' }]);
assert.equal((await q(`select count(*)::int n from journal_caisse where source = 'photo' and nb_ventes = 1`))[0].n, 1);
await assert.rejects(q(`select enregistrer_ventes_photo((now() at time zone 'Europe/Paris')::date + 1, '[{"nom_produit":"Flan","quantite":3}]', null)`), /Date/);
assert.equal((await q(`select count(*)::int n from ventes_horaires where nom_produit = 'Flan'`))[0].n, 0); // la photo n'écrit pas les heures
// Rapports « à confirmer » (photo / PDF / texte reçus par e-mail, lus par l'IA).
await q(`insert into rapports_a_confirmer (commercant_id, jour, lignes) values ($1, null, '[{"nom_produit":"Éclair","quantite":4}]'), ($1, null, '[{"nom_produit":"Mille-feuille","quantite":2}]')`, [C]);
const [r1, r2] = (await q(`select id from rapports_a_confirmer order by id`)).map(r => r.id);
const hier = `(now() at time zone 'Europe/Paris')::date - 1`;
for (const role of ['anon', 'authenticated']) {
  for (const droit of ['insert', 'update', 'delete']) assert.equal((await q(`select has_table_privilege('${role}', 'rapports_a_confirmer', '${droit}') ok`))[0].ok, false, role + droit);
  assert.equal((await q(`select has_function_privilege('${role}', 'confirmer_rapport(bigint,date,jsonb)', 'execute') ok`))[0].ok, role === 'authenticated');
}
// Rien n'entre dans les ventes avant la confirmation.
assert.equal((await q(`select count(*)::int n from ventes where nom_produit = 'Éclair'`))[0].n, 0);
await assert.rejects(q(`select confirmer_rapport($1, ${hier} + 5, '[{"nom_produit":"Éclair","quantite":4}]')`, [r1]), /Date/);
await assert.rejects(q(`select confirmer_rapport($1, ${hier}, '[]')`, [r1]), /lignes/);
// Confirmé avec une correction du boulanger (4 -> 6), source export_email, une ligne de journal.
assert.equal((await q(`select confirmer_rapport($1, ${hier}, '[{"nom_produit":"Éclair","quantite":6},{"nom_produit":"éclairs","quantite":1}]') n`, [r1]))[0].n, 1);
assert.deepEqual(await q(`select nom_produit, quantite::int, source from ventes where nom_produit = 'Éclair'`), [{ nom_produit: 'Éclair', quantite: 7, source: 'export_email' }]);
assert.equal((await q(`select count(*)::int n from journal_caisse where detail = 'Rapport confirmé par toi' and nb_ventes = 1`))[0].n, 1);
await assert.rejects(q(`select confirmer_rapport($1, ${hier}, '[{"nom_produit":"Éclair","quantite":4}]')`, [r1]), /déjà traité/); // deux fois : jamais
// Rejeté : rien dans les ventes, et plus confirmable.
await q(`select rejeter_rapport($1)`, [r2]);
assert.deepEqual((await q(`select statut from rapports_a_confirmer where id = $1`, [r2])).map(r => r.statut), ['rejete']);
await assert.rejects(q(`select confirmer_rapport($1, ${hier}, '[{"nom_produit":"Mille-feuille","quantite":2}]')`, [r2]), /déjà traité/);
assert.equal((await q(`select count(*)::int n from ventes where nom_produit = 'Mille-feuille'`))[0].n, 0);
// Le rapport d'un autre commerçant n'est pas touchable.
await q(`insert into auth.users values ('00000000-0000-0000-0000-000000000002')`);
await q(`insert into rapports_a_confirmer (commercant_id, lignes) values ('00000000-0000-0000-0000-000000000002', '[{"nom_produit":"X","quantite":1}]')`);
const [rAutre] = (await q(`select id from rapports_a_confirmer where commercant_id = '00000000-0000-0000-0000-000000000002'`)).map(r => r.id);
await assert.rejects(q(`select confirmer_rapport($1, ${hier}, '[{"nom_produit":"X","quantite":1}]')`, [rAutre]), /introuvable/);
console.log('migration OK');
