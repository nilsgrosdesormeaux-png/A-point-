// Teste migration-connecteurs-caisse.sql dans un vrai Postgres (PGlite, en
// mémoire) sans toucher au projet Supabase : normalisation, dédoublonnage,
// relance sans doublon, droits et RLS.
// Lancement : npm i --no-save @electric-sql/pglite@0.3.7 && node tests/caisse-migration.test.mjs

import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
// Socle minimal imitant Supabase (auth.users, rôles, ventes, produits tels qu'en prod).
await db.exec(`
  create schema auth; create table auth.users (id uuid primary key);
  create or replace function auth.uid() returns uuid language sql as $$ select null::uuid $$;
  create role anon; create role authenticated; create role service_role;
  create table ventes (id bigint generated by default as identity primary key, created_at timestamptz default now(),
    nom_produit text, quantite bigint, date_vente date, commercant_id uuid);
  create table produits (id bigint generated by default as identity primary key, created_at timestamptz default now(),
    commercant_id uuid default gen_random_uuid(), nom text, categorie_id text);
  insert into auth.users values ('00000000-0000-0000-0000-000000000001');
`);
await db.exec(fs.readFileSync(new URL('../migration-connecteurs-caisse.sql', import.meta.url), 'utf8'));
const C = '00000000-0000-0000-0000-000000000001';
const q = async (s, p) => (await db.query(s, p)).rows;

for (const [entree, attendu] of [['  Croissants ', 'croissant'], ['CROISSANT', 'croissant'], ['Éclair café', 'eclair cafe'], ['Gâteaux', 'gateau'], ['Bus', 'bus'], [null, '']]) {
  assert.equal((await q('select normaliser_nom_produit($1) n', [entree]))[0].n, attendu, String(entree));
}

// Existant : produit "Pain au chocolat", saisie manuelle du 29 (5) et du 28 (7).
await q(`insert into produits (commercant_id, nom) values ($1, 'Pain au chocolat')`, [C]);
await q(`insert into ventes (commercant_id, nom_produit, quantite, date_vente) values ($1,'Pain au chocolat',5,'2026-10-29'),($1,'pain au chocolat ',7,'2026-10-28')`, [C]);

const lignes = [
  { nom_produit: 'PAIN AU CHOCOLATS', quantite: 30, date_vente: '2026-10-29' },
  { nom_produit: 'Pain au chocolat', quantite: 2, date_vente: '2026-10-29' },
  { nom_produit: 'Baguette', quantite: 80.4, date_vente: '2026-10-29' },
  { nom_produit: 'Baguette', quantite: -3, date_vente: '2026-10-30' },
  { nom_produit: '  ', quantite: 9, date_vente: '2026-10-29' }
];
assert.equal((await q(`select enregistrer_ventes_caisse($1, $2::jsonb, 'sumup') n`, [C, JSON.stringify(lignes)]))[0].n, 3);
// Relance identique : aucun doublon.
await q(`select enregistrer_ventes_caisse($1, $2::jsonb, 'sumup')`, [C, JSON.stringify(lignes)]);

const v = await q(`select nom_produit, quantite::int, date_vente::text, source from ventes order by date_vente, nom_produit`);
console.log(v);
assert.deepEqual(v, [
  { nom_produit: 'pain au chocolat ', quantite: 7, date_vente: '2026-10-28', source: 'manuel' },
  { nom_produit: 'Baguette', quantite: 80, date_vente: '2026-10-29', source: 'sumup' },
  { nom_produit: 'Pain au chocolat', quantite: 32, date_vente: '2026-10-29', source: 'sumup' },
  { nom_produit: 'Baguette', quantite: 0, date_vente: '2026-10-30', source: 'sumup' }
]);
assert.deepEqual((await q('select nom from produits order by id')).map(r => r.nom), ['Pain au chocolat', 'Baguette']);

// Droits : seul service_role peut appeler la fonction d'enregistrement.
for (const role of ['anon', 'authenticated']) {
  assert.equal((await q(`select has_function_privilege('${role}', 'enregistrer_ventes_caisse(uuid,jsonb,text)', 'execute') ok`))[0].ok, false);
}
assert.equal((await q(`select has_function_privilege('service_role', 'enregistrer_ventes_caisse(uuid,jsonb,text)', 'execute') ok`))[0].ok, true);
// RLS active partout, secrets sans aucune policy.
const rls = await q(`select relname, relrowsecurity from pg_class where relname in ('connexions_caisse','connexions_caisse_secrets','etats_oauth_caisse')`);
assert.ok(rls.every(r => r.relrowsecurity));
assert.equal((await q(`select count(*)::int n from pg_policies where tablename in ('connexions_caisse_secrets','etats_oauth_caisse')`))[0].n, 0);
console.log('migration OK');
